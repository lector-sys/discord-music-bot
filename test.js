import assert from 'node:assert/strict';
import {
  BAR_WIDTH,
  HISTORY_CAP,
  bestThumbnail,
  clampVolume,
  cleanError,
  fmt,
  kindOf,
  loopEmoji,
  nextLoop,
  normalize,
  pickResult,
  planJump,
  planPrevious,
  progressBar,
  pushHistory,
} from './src/player.js';

// normalize() only rescues scheme-less YouTube links; anything it rejects goes to
// kindOf() raw, which classifies it as a search term.
const kind = (s) => kindOf(normalize(s) ?? s);

assert.equal(kind('https://www.youtube.com/watch?v=dQw4w9WgXcQ'), 'video');
assert.equal(kind('https://youtu.be/dQw4w9WgXcQ?si=abc'), 'video');
assert.equal(kind('https://www.youtube.com/shorts/abc123'), 'video');
assert.equal(kind('https://music.youtube.com/watch?v=dQw4w9WgXcQ'), 'video');
assert.equal(kind('https://www.youtube.com/playlist?list=PL123'), 'playlist');
// Video opened from inside a playlist -> queue the whole playlist...
assert.equal(kind('https://www.youtube.com/watch?v=dQw4w9WgXcQ&list=PL123'), 'playlist');
// ...but an autogenerated mix is endless, so treat it as the single video.
assert.equal(kind('https://www.youtube.com/watch?v=dQw4w9WgXcQ&list=RD123'), 'video');

// Forms people actually paste (these all used to be rejected).
assert.equal(kind('youtube.com/watch?v=dQw4w9WgXcQ'), 'video');
assert.equal(kind('www.youtube.com/watch?v=dQw4w9WgXcQ'), 'video');
assert.equal(kind('  https://youtu.be/dQw4w9WgXcQ  '), 'video');
assert.equal(kind('<https://www.youtube.com/watch?v=dQw4w9WgXcQ>'), 'video');

// Not a usable YouTube video/playlist URL -> search for it rather than erroring out.
assert.equal(kind('never gonna give you up'), 'search');
assert.equal(kind('https://vimeo.com/12345'), 'search');
assert.equal(kind('https://notyoutube.com/watch?v=x'), 'search');
assert.equal(kind('evil.com/youtube.com/watch?v=x'), 'search');
assert.equal(kind('not a url'), 'search');
assert.equal(kind('https://www.youtube.com/'), 'search');
assert.equal(kind(''), 'search');
assert.equal(kind(undefined), 'search');
// A truncated paste searches instead of throwing.
assert.equal(kind('youtube.com/watch?v='), 'search');
assert.equal(kind('https://www.youtube.com/watch?v='), 'search');
assert.equal(kind('https://youtu.be/'), 'search');

// Where the scheme-less boundary sits: normalize() adds https:// for YouTube hosts only,
// so a URL-shaped string on any other host stays free text.
assert.equal(kind('youtube.com/watch?v=dQw4w9WgXcQ'), 'video');
assert.equal(kind('example.com/watch?v=dQw4w9WgXcQ'), 'search');
assert.equal(kind('youtube.com'), 'search'); // no path -> normalize() will not touch it

// pickResult: skip livestreams and zero-duration premieres, which never end and so
// park in the queue past the idle-leave timer.
const live = { title: 'lofi 24/7', is_live: true, duration: 0 };
const upcoming = { title: 'premiere', live_status: 'is_live', duration: 0 };
const zero = { title: 'placeholder', duration: 0 };
const real = { title: 'the song', duration: 213 };
const other = { title: 'a cover', duration: 198 };

assert.equal(pickResult([real, other]), real); // normal case: take the top hit
assert.equal(pickResult([live, real]), real); // top hit is a livestream
assert.equal(pickResult([zero, real]), real); // top hit has no duration
assert.equal(pickResult([upcoming, real]), real); // live_status flags it too
assert.equal(pickResult([live, upcoming]), live); // all unplayable -> fall back to the top
assert.equal(pickResult([]), null); // nothing found -> caller throws

assert.equal(fmt(0), '0:00');
assert.equal(fmt(9), '0:09');
assert.equal(fmt(605), '10:05');

// yt-dlp stderr -> something a human wants to read
assert.equal(
  cleanError('ERROR: [youtube] abc12345678: Sign in to confirm your age'),
  'age-restricted',
);
assert.equal(cleanError('ERROR: [youtube] abc12345678: Private video'), 'private');
assert.equal(cleanError('ERROR: [youtube] abc12345678: Video unavailable'), 'unavailable');
assert.equal(cleanError('WARNING: something noisy'), 'could not be fetched');

// Volume clamps at both ends; the panel steps by 10 and must not run past the bounds.
assert.equal(clampVolume(50), 50);
assert.equal(clampVolume(0 - 10), 0);
assert.equal(clampVolume(100 + 10), 100);
assert.equal(clampVolume(-999), 0);
assert.equal(clampVolume(999), 100);

// Loop cycles off -> track -> queue and wraps; anything unexpected lands on off.
assert.equal(nextLoop('off'), 'track');
assert.equal(nextLoop('track'), 'queue');
assert.equal(nextLoop('queue'), 'off');
assert.equal(nextLoop(undefined), 'off');

// History is bounded: the oldest entries fall off, the newest survive.
const h = [];
for (let i = 0; i < HISTORY_CAP + 5; i++) pushHistory(h, { title: `t${i}` });
assert.equal(h.length, HISTORY_CAP);
assert.equal(h[0].title, 't5'); // t0..t4 evicted
assert.equal(h.at(-1).title, `t${HISTORY_CAP + 4}`);
assert.equal(pushHistory([], null).length, 0); // nothing playing, nothing to record

// Previous with history: play the popped track, send the current one back to the queue.
const past = [{ title: 'a' }, { title: 'b' }];
const now = { title: 'c' };
const back = planPrevious(past, now);
assert.equal(back.track.title, 'b');
assert.equal(back.requeue, now);
assert.equal(past.length, 1);

// Previous with no history restarts the current track instead of doing nothing.
const restart = planPrevious([], now);
assert.equal(restart.track, now);
assert.equal(restart.requeue, null);

// Progress bar: fixed width, head at the left on 0% and the right on 100%.
assert.equal(progressBar(0, 100), `●${'─'.repeat(BAR_WIDTH - 1)}`);
assert.equal(progressBar(50, 100), `${'━'.repeat(8)}●${'─'.repeat(7)}`);
assert.equal(progressBar(100, 100), `${'━'.repeat(BAR_WIDTH - 1)}●`);
// A livestream has no total to fill, so the head stays parked rather than dividing by zero.
assert.equal(progressBar(500, 0), `●${'─'.repeat(BAR_WIDTH - 1)}`);
// Width holds whatever you throw at it, including out-of-range input.
for (const [e, t] of [[0, 0], [10, 100], [999, 100], [-5, 100], [1, 3]]) {
  assert.equal([...progressBar(e, t)].length, BAR_WIDTH, `width for ${e}/${t}`);
}

// Loop emoji tracks the mode, and anything unexpected falls back to 'off'.
assert.equal(loopEmoji('off'), '➡️');
assert.equal(loopEmoji('track'), '🔂');
assert.equal(loopEmoji('queue'), '🔁');
assert.equal(loopEmoji(undefined), loopEmoji('off'));
assert.notEqual(loopEmoji('track'), loopEmoji('queue'));

// Artwork: prefer the widest thumbnail yt-dlp gave us, else derive one from the id.
assert.equal(
  bestThumbnail({ thumbnails: [{ url: 'small', width: 360 }, { url: 'big', width: 720 }] }),
  'big',
);
assert.equal(bestThumbnail({ id: 'abc123' }), 'https://i.ytimg.com/vi/abc123/hqdefault.jpg');
assert.equal(bestThumbnail({}), null);
assert.equal(bestThumbnail(null), null);

// Jumping to queue[2]: the playing track goes back first, then the tracks jumped
// over, so Previous walks back through them in the order they were listed.
const jHist = [{ t: 'old' }];
const jQueue = [{ t: 'b' }, { t: 'c' }, { t: 'target' }, { t: 'e' }];
const playing = { t: 'a' };
assert.equal(planJump(jHist, jQueue, playing, 2), true);
assert.deepEqual(jHist.map((x) => x.t), ['old', 'a', 'b', 'c']);
assert.deepEqual(jQueue.map((x) => x.t), ['target', 'e']); // target is now next up

// Index 0 is "play the very next track": nothing is jumped over, only the current
// track goes back.
const zHist = [];
const zQueue = [{ t: 'next' }, { t: 'after' }];
assert.equal(planJump(zHist, zQueue, { t: 'now' }, 0), true);
assert.deepEqual(zHist.map((x) => x.t), ['now']);
assert.deepEqual(zQueue.map((x) => x.t), ['next', 'after']);

// Out-of-range and junk indexes change nothing at all.
for (const bad of [-1, 2, 99, 1.5, NaN, undefined, '1']) {
  const h = [{ t: 'keep' }];
  const q = [{ t: 'x' }, { t: 'y' }];
  assert.equal(planJump(h, q, { t: 'now' }, bad), false, `index ${bad}`);
  assert.equal(h.length, 1, `history untouched for ${bad}`);
  assert.equal(q.length, 2, `queue untouched for ${bad}`);
}

console.log('ok');
