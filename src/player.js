import { spawn } from 'node:child_process';
import {
  AudioPlayerStatus,
  NoSubscriberBehavior,
  StreamType,
  VoiceConnectionStatus,
  createAudioPlayer,
  createAudioResource,
  entersState,
  joinVoiceChannel,
} from '@discordjs/voice';
import ytdlExec from 'youtube-dl-exec';

const YTDLP = ytdlExec.constants.YOUTUBE_DL_PATH;
const IDLE_MS = Number(process.env.IDLE_TIMEOUT_MS ?? 300_000);

// Opus-in-WebM only: @discordjs/voice demuxes it straight through, so no ffmpeg
// and no transcoding. If YouTube has no such format we want a loud failure, not
// an m4a stream fed to a WebM demuxer.
const AUDIO_FORMAT = 'bestaudio[acodec=opus][ext=webm]/bestaudio[ext=webm]';

export const fmt = (sec) =>
  `${Math.floor(sec / 60)}:${String(Math.floor(sec % 60)).padStart(2, '0')}`;

/** Tidy up what people actually paste: whitespace, Discord's <...>, missing scheme. */
export function normalize(input) {
  const s = String(input ?? '')
    .trim()
    .replace(/^<+|>+$/g, '')
    .trim();
  if (!s) return null;
  if (/^https?:\/\//i.test(s)) return s;
  if (/^(www\.|m\.|music\.)?(youtube\.com|youtube-nocookie\.com|youtu\.be)\//i.test(s)) {
    return `https://${s}`;
  }
  return null;
}

/**
 * 'playlist' | 'video' | 'search'. Anything that is not a recognized YouTube
 * video/playlist URL — free text, a foreign host, a truncated paste — is a
 * search term. A broken paste is better served by a search than an error.
 */
export function kindOf(url) {
  let u;
  try {
    u = new URL(url);
  } catch {
    return 'search';
  }
  if (!/(^|\.)(youtube\.com|youtube-nocookie\.com|youtu\.be)$/.test(u.hostname)) return 'search';

  // A watch URL carrying &list= is "video inside a playlist" — queue the whole list,
  // except autogenerated mixes (RD...), which are endless.
  const list = u.searchParams.get('list');
  if (list && !list.startsWith('RD')) return 'playlist';
  if (u.pathname === '/playlist') return 'search'; // /playlist with no usable list=

  if (u.hostname === 'youtu.be' ? u.pathname.length > 1 : u.searchParams.get('v')) return 'video';
  if (u.pathname.startsWith('/shorts/') || u.pathname.startsWith('/live/')) return 'video';
  return 'search';
}

/**
 * Pick a playable hit out of search results: first one that is neither a
 * livestream nor zero-duration, else the top hit.
 *
 * The top result for a song title is often a 24/7 radio livestream or a
 * zero-duration premiere placeholder. Either one sits in the queue forever —
 * audio technically keeps flowing, so the idle-leave timer never fires.
 */
export function pickResult(results) {
  const isLive = (r) => Boolean(r?.is_live) || r?.live_status === 'is_live';
  return results.find((r) => !isLive(r) && (r?.duration ?? 0) > 0) ?? results[0] ?? null;
}

/** yt-dlp's ERROR: line, stripped of its prefixes and made presentable. */
export function cleanError(stderr) {
  const line = String(stderr)
    .split('\n')
    .find((l) => l.startsWith('ERROR:'));
  const msg = (line ?? '')
    .replace(/^ERROR:\s*/, '')
    .replace(/^\[[^\]]+\]\s*/, '')
    .replace(/^[\w-]{11}:\s*/, '')
    .trim();
  if (/age|sign in to confirm|inappropriate/i.test(msg)) return 'age-restricted';
  if (/private/i.test(msg)) return 'private';
  if (/not available in your country|geo|region/i.test(msg)) return 'region-locked';
  if (/unavailable|removed|terminated/i.test(msg)) return 'unavailable';
  if (/requested format/i.test(msg)) return 'no playable audio track';
  return msg.slice(0, 150) || 'could not be fetched';
}

function runYtdlp(args, timeoutMs = 60_000) {
  return new Promise((res, rej) => {
    const child = spawn(YTDLP, args, { windowsHide: true });
    let out = '';
    let err = '';
    const timer = setTimeout(() => {
      child.kill('SIGKILL');
      rej(new Error('YouTube took too long to respond. Try again.'));
    }, timeoutMs);

    child.stdout.on('data', (c) => (out += c));
    child.stderr.on('data', (c) => (err += c));
    child.on('error', () => {
      clearTimeout(timer);
      rej(new Error('Could not run yt-dlp. Try `npm install` again.'));
    });
    child.on('close', (code) => {
      clearTimeout(timer);
      if (code === 0) res(out);
      else rej(new Error(cleanError(err)));
    });
  });
}

const toTrack = (e) => ({
  title: e.title ?? 'Unknown title',
  url: e.webpage_url ?? e.url,
  duration: e.duration ?? 0,
  channel: e.channel ?? e.uploader ?? null,
});

/** URL or search terms -> { name, tracks, searched }. Throws user-facing messages. */
export async function resolve(input) {
  const query = String(input ?? '')
    .trim()
    .replace(/^<+|>+$/g, '')
    .trim();
  const url = normalize(query);
  const kind = kindOf(url ?? query);

  if (kind === 'search') {
    if (!query) throw new Error('Give me a YouTube link or something to search for.');
    const found = JSON.parse(
      await runYtdlp([
        `ytsearch5:${query}`,
        '--dump-single-json',
        '--flat-playlist',
        '--no-warnings',
      ]),
    );
    const hit = pickResult(found.entries ?? []);
    if (!hit) throw new Error(`No YouTube results for **${query}**.`);
    return { name: null, tracks: [toTrack(hit)], searched: true };
  }

  const data = JSON.parse(
    await runYtdlp([
      url,
      '--dump-single-json',
      '--flat-playlist',
      '--no-warnings',
      kind === 'playlist' ? '--yes-playlist' : '--no-playlist',
    ]),
  );

  if (data._type === 'playlist') {
    const tracks = (data.entries ?? [])
      .filter((e) => e?.url && !/^\[(deleted|private|unavailable)/i.test(e.title ?? ''))
      .map(toTrack);
    if (!tracks.length) throw new Error('That playlist is empty, private, or fully unavailable.');
    return { name: data.title ?? 'playlist', tracks };
  }
  return { name: null, tracks: [toTrack(data)] };
}

export class GuildPlayer {
  constructor(guild, textChannel) {
    this.guild = guild;
    this.text = textChannel;
    this.queue = [];
    this.current = null;
    this.connection = null;
    this.child = null;
    this.timer = null;
    this.dead = false;

    this.player = createAudioPlayer({ behaviors: { noSubscriber: NoSubscriberBehavior.Play } });
    this.player.on('stateChange', (from, to) =>
      console.log(`[player] ${from.status} -> ${to.status}`),
    );
    this.player.on(AudioPlayerStatus.Idle, () => {
      this.#next().catch((err) => console.error(err));
    });
    // The player goes Idle on its own after an error, which advances the queue — do not advance here too.
    this.player.on('error', (err) => {
      console.error(err);
      this.say(`⚠️ Playback error on **${this.current?.title ?? 'track'}**.`);
    });
  }

  say(msg) {
    this.text?.send(msg).catch(() => {});
  }

  async connect(channel) {
    if (!this.connection) {
      this.connection = joinVoiceChannel({
        channelId: channel.id,
        guildId: channel.guild.id,
        adapterCreator: channel.guild.voiceAdapterCreator,
        selfDeaf: true,
      });
      this.connection.subscribe(this.player);
      this.connection.on('stateChange', (from, to) =>
        console.log(`[voice] ${from.status} -> ${to.status}`),
      );
      this.connection.on('error', (err) => console.error('[voice]', err));
      this.#watchDisconnect();
    }
    // Audio pushed before the UDP handshake finishes is silently discarded.
    try {
      await entersState(this.connection, VoiceConnectionStatus.Ready, 20_000);
    } catch {
      this.destroy();
      throw new Error(
        'Could not establish the voice connection (UDP blocked, or Discord voice is having a moment). Try again.',
      );
    }
  }

  #watchDisconnect() {
    this.connection.on(VoiceConnectionStatus.Disconnected, async () => {
      try {
        await Promise.race([
          entersState(this.connection, VoiceConnectionStatus.Signalling, 5_000),
          entersState(this.connection, VoiceConnectionStatus.Connecting, 5_000),
        ]);
      } catch {
        this.destroy(); // moved out or kicked, not a resumable hiccup
      }
    });
  }

  async add(tracks) {
    this.queue.push(...tracks);
    this.cancelLeave();
    if (!this.current) await this.#next();
  }

  #killChild() {
    if (!this.child) return;
    this.child.killedByUs = true;
    this.child.kill('SIGKILL');
    this.child = null;
  }

  /** Spawns yt-dlp piping Opus/WebM to stdout. Reports why a track died, if it does. */
  #audioStream(track) {
    const child = spawn(
      YTDLP,
      [track.url, '-f', AUDIO_FORMAT, '-o', '-', '--no-playlist', '--quiet', '--no-warnings'],
      { windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'] },
    );
    this.child = child;

    let err = '';
    child.stderr.on('data', (c) => (err += c));
    child.on('error', () => this.say('⚠️ Could not run yt-dlp.'));
    child.on('close', (code) => {
      // A nonzero exit we did not cause means this track never played.
      if (!child.killedByUs && code !== 0) {
        this.say(`⏭️ Skipping **${track.title}** — ${cleanError(err)}.`);
      }
    });
    return child.stdout;
  }

  async #next() {
    if (this.dead) return;
    this.cancelLeave();
    this.#killChild();

    this.current = this.queue.shift() ?? null;
    if (!this.current) {
      this.scheduleLeave();
      return;
    }
    this.player.play(
      createAudioResource(this.#audioStream(this.current), { inputType: StreamType.WebmOpus }),
    );
    this.say(`▶️ Now playing **${this.current.title}** \`${fmt(this.current.duration)}\``);
  }

  skip() {
    this.#killChild();
    this.player.stop(true); // Idle fires -> #next
  }

  pause() {
    return this.player.pause();
  }

  resume() {
    return this.player.unpause();
  }

  scheduleLeave() {
    this.cancelLeave();
    if (this.dead) return;
    this.timer = setTimeout(
      () => this.destroy(`👋 Left the channel after ${Math.round(IDLE_MS / 60_000)} min idle.`),
      IDLE_MS,
    );
  }

  cancelLeave() {
    clearTimeout(this.timer);
    this.timer = null;
  }

  /** Called on every voiceStateUpdate in this guild. */
  checkListeners() {
    const channelId = this.connection?.joinConfig.channelId;
    if (!channelId) return;
    // ponytail: counts other bots as listeners; filter by member.user.bot if that ever matters.
    const others = this.guild.voiceStates.cache.filter(
      (v) => v.channelId === channelId && v.id !== this.guild.client.user.id,
    ).size;
    if (others === 0) this.scheduleLeave();
    else if (this.current) this.cancelLeave();
  }

  destroy(msg) {
    this.dead = true;
    this.cancelLeave();
    this.#killChild();
    this.queue = [];
    this.current = null;
    this.player.stop(true);
    try {
      this.connection?.destroy();
    } catch {}
    this.connection = null;
    this.onDestroy?.();
    if (msg) this.say(msg);
  }
}
